FIRST, LAST = 32, 126
H = {"S": (15, 11), "M": (19, 14)}          # line height, baseline (one up from the standard faces: the capitals sit centred in odd boxes)


def face(name):
    """-> [(adv16, bx, by, bw, bh, bitmap rows)] per glyph in table order, cap rows"""
    h, asc = H[name]
    ncap = 7 if name == "S" else 9
    out = []
    chars = [chr(c) for c in range(FIRST, LAST + 1)] + [chr(c) if t is None else t for c, t in EXTRAS]
    for ch in chars:
        rows = G[ch]
        main, desc = rows[:7], rows[7:]
        if name == "M":                    # 7 rows -> 9 (rows 2 and 5 twice), bold: one pixel to the right
            main = [main[i] for i in (0, 1, 2, 2, 3, 4, 5, 5, 6)]
            rows = main + desc
            rows = ["".join("#" if (r[i] == "#" or (i and r[i - 1] == "#")) else "." for i in range(5)) + ("#" if r[4] == "#" else ".")
                    for r in rows]
        else:
            main = list(main)
            rows = main + list(desc)
        w = len(rows[0])
        top = asc - len(main)              # canvas row of the first row
        ys = [i for i, r in enumerate(rows) if "#" in r]
        if not ys:
            out.append((16 * (w + 1), 0, 0, 0, 0, []))
            continue
        y0, y1 = ys[0], ys[-1] + 1
        xs = [i for r in rows[y0:y1] for i, c in enumerate(r) if c == "#"]
        x0, x1 = min(xs), max(xs) + 1
        bm = [r[x0:x1] for r in rows[y0:y1]]
        out.append((16 * (w + 1), x0, top + y0, x1 - x0, y1 - y0, bm))
    return h, asc, ncap, out


def emit(name, pre="AP_"):
    h, asc, ncap, gl = face(name)
    data, table = bytearray(), []
    for adv, bx, by, bw, bh, bm in gl:
        table.append((len(data), adv, bx, by, bw, bh))
        v = [15 if c == "#" else 0 for r in bm for c in r]
        if len(v) & 1:
            v.append(0)
        data += bytes((v[i] << 4) | v[i + 1] for i in range(0, len(v), 2))
    n = len(table)
    lines = [f"/* {name}: hand-drawn 5 x 7 bitmap face, h {h}, baseline {asc}, {n} glyphs, {len(data)} B data */",
             f"static const uint8_t {pre}{name}_DATA[{len(data)}] = {{"]
    for i in range(0, len(data), 24):
        lines.append("    " + ", ".join(f"0x{b:02x}" for b in data[i:i + 24]) + ",")
    lines.append("};")
    lines.append(f"static const aag_t {pre}{name}_G[{n}] = {{")
    for off, adv, bx, by, bw, bh in table:
        lines.append(f"    {{{off}, {adv}, {bx}, {by}, {bw}, {bh}}},")
    lines.append("};")
    lines.append(f"static const uint8_t {pre}{name}_EX[{len(EXTRAS)}] = {{{', '.join(str(c) for c, _ in EXTRAS)}}};")
    lines.append(f"static const aafont_t {pre}{name} = {{{h}, {asc}, {FIRST}, {LAST}, {len(EXTRAS)}, 0, {pre}{name}_G, "
                 f"{pre}{name}_DATA, 0, 0, {pre}{name}_EX, 0, 0}};")
    hh = gl[ord("H") - FIRST]
    lines.append(f"#define {pre}{name}_CAP_Y {hh[2]}   /* the ink of H: rows {hh[2]} .. {hh[2] + hh[4] - 1} of the line */")
    lines.append(f"#define {pre}{name}_CAP_H {hh[4]}")
    return "\n".join(lines) + "\n", len(data) + 8 * n


def main():
    out = ["/* generated by tools/gen_px_font.py: the RETRO bitmap faces (hand-drawn, 4-bit alpha 0 / 15) */",
           "#pragma once", "#include <stdint.h>", ""]
    tot = 0
    for name in "SM":
        t, c = emit(name)
        out.append(t)
        tot += c
        print(f"face {name}: {c} B")
    Path(sys.argv[1]).write_text("\n".join(out))
    print(f"pixel fonts total {tot} B -> {sys.argv[1]}")


if __name__ == "__main__":
    main()
